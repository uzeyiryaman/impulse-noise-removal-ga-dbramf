def compute_binary_impulse_mask(noisy_image):
    """
    Detect binary impulse noise pixels.
    """
    return (noisy_image == 0) | (noisy_image == 255)


def compute_fixed_rvin_outlier_mask(noisy_image, threshold=45):
    """
    Fixed-threshold RVIN detector used in the first report.
    """
    local_median = cv2.medianBlur(noisy_image.astype(np.uint8), 3)

    difference = np.abs(
        noisy_image.astype(np.int16) - local_median.astype(np.int16)
    )

    return difference > threshold


def compute_adaptive_rvin_outlier_mask(
    noisy_image,
    base_threshold=18,
    mad_weight=2.5,
    median_kernel_size=3,
    mad_kernel_size=7,
    minimum_threshold=22,
    maximum_threshold=85
):
    """
    Adaptive RVIN detector.

    The threshold is adjusted according to local median absolute deviation.
    This makes the detector less aggressive in textured regions and more
    sensitive in smooth regions.
    """
    noisy_uint8 = noisy_image.astype(np.uint8)

    local_median = cv2.medianBlur(noisy_uint8, median_kernel_size)

    difference = np.abs(
        noisy_uint8.astype(np.int16) - local_median.astype(np.int16)
    ).astype(np.uint8)

    local_mad = cv2.medianBlur(difference, mad_kernel_size).astype(np.float32)

    adaptive_threshold = base_threshold + mad_weight * local_mad
    adaptive_threshold = np.clip(
        adaptive_threshold,
        minimum_threshold,
        maximum_threshold
    )

    adaptive_mask = difference.astype(np.float32) > adaptive_threshold

    return adaptive_mask


def calculate_detector_metrics(true_mask, predicted_mask):
    """
    Calculate precision, recall, and F1-score for corruption detection.
    """
    true_mask = true_mask.astype(bool)
    predicted_mask = predicted_mask.astype(bool)

    true_positive = np.logical_and(true_mask, predicted_mask).sum()
    false_positive = np.logical_and(~true_mask, predicted_mask).sum()
    false_negative = np.logical_and(true_mask, ~predicted_mask).sum()
    true_negative = np.logical_and(~true_mask, ~predicted_mask).sum()

    precision = true_positive / (true_positive + false_positive + 1e-12)
    recall = true_positive / (true_positive + false_negative + 1e-12)
    f1_score = 2 * precision * recall / (precision + recall + 1e-12)
    accuracy = (true_positive + true_negative) / true_mask.size

    return {
        "TP": int(true_positive),
        "FP": int(false_positive),
        "FN": int(false_negative),
        "TN": int(true_negative),
        "Precision": float(precision),
        "Recall": float(recall),
        "F1_Score": float(f1_score),
        "Accuracy": float(accuracy)
    }


