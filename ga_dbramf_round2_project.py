def apply_standard_median_filter(noisy_image, kernel_size=3):
    """
    Apply standard median filtering to a noisy grayscale image.

    Parameters
    ----------
    noisy_image : numpy.ndarray
        Noisy grayscale image in uint8 format.
    kernel_size : int
        Size of the median filter kernel. It must be an odd integer.

    Returns
    -------
    filtered_image : numpy.ndarray
        Median filtered grayscale image.
    """

    if kernel_size % 2 == 0:
        raise ValueError("Kernel size must be an odd integer.")

    filtered_image = cv2.medianBlur(noisy_image.astype(np.uint8), kernel_size)

    return filtered_image.astype(np.uint8)

