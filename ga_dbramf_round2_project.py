"""## Proposed GA-DBRAMF

In this section, the proposed Gradient-Aware Decision-Based Recursive Adaptive Median Filter is implemented.

The method follows these steps:
1. Detect corrupted pixels.
2. Keep healthy pixels unchanged.
3. For corrupted pixels, search healthy pixels in a 3 x 3 window.
4. If no healthy pixel exists, expand the search to a 5 x 5 window.
5. If the maximum window still contains no healthy pixel, apply Gradient-Aware Directional Interpolation.

The gradient-aware fallback evaluates four directions:
- 0 degrees
- 45 degrees
- 90 degrees
- 135 degrees

The direction with the minimum gradient is selected for interpolation.
"""

# Corruption mask functions for GA-DBRAMF

def compute_binary_impulse_mask(noisy_image):
    """
    Compute corrupted pixel mask for binary impulse noise.

    A pixel is considered corrupted if its value is 0 or 255.

    Parameters
    ----------
    noisy_image : numpy.ndarray
        Noisy grayscale image.

    Returns
    -------
    corrupted_mask : numpy.ndarray
        Boolean mask where True indicates corrupted pixels.
    """

    corrupted_mask = (noisy_image == 0) | (noisy_image == 255)
    return corrupted_mask


def compute_rvin_outlier_mask(noisy_image, threshold=45, median_kernel_size=3):
    """
    Compute an approximate corrupted pixel mask for Random-Valued Impulse Noise.

    A pixel is considered suspicious if it differs strongly from the local median.

    Parameters
    ----------
    noisy_image : numpy.ndarray
        Noisy grayscale image.
    threshold : int
        Absolute intensity difference threshold.
    median_kernel_size : int
        Kernel size for local median estimation.

    Returns
    -------
    corrupted_mask : numpy.ndarray
        Boolean mask where True indicates detected outlier pixels.
    """

    local_median = cv2.medianBlur(noisy_image.astype(np.uint8), median_kernel_size)

    difference = np.abs(
        noisy_image.astype(np.int16) - local_median.astype(np.int16)
    )

    corrupted_mask = difference > threshold

    return corrupted_mask


def compute_corrupted_mask(noisy_image, detection_mode="binary", rvin_threshold=45):
    """
    Compute corrupted pixel mask according to the selected detection mode.

    Parameters
    ----------
    noisy_image : numpy.ndarray
        Noisy grayscale image.
    detection_mode : str
        Detection mode. Options: "binary" or "rvin".
    rvin_threshold : int
        Threshold used for RVIN outlier detection.

    Returns
    -------
    corrupted_mask : numpy.ndarray
        Boolean corrupted pixel mask.
    """

    if detection_mode == "binary":
        return compute_binary_impulse_mask(noisy_image)

    if detection_mode == "rvin":
        return compute_rvin_outlier_mask(
            noisy_image,
            threshold=rvin_threshold,
            median_kernel_size=3
        )

    raise ValueError("detection_mode must be either 'binary' or 'rvin'.")

# Window helper functions for GA-DBRAMF

def extract_window_with_mask(image, mask, x, y, window_size):
    """
    Extract a local image window and the corresponding mask window.

    Parameters
    ----------
    image : numpy.ndarray
        Input image.
    mask : numpy.ndarray
        Boolean corrupted pixel mask.
    x : int
        Row index.
    y : int
        Column index.
    window_size : int
        Local window size.

    Returns
    -------
    image_window : numpy.ndarray
        Extracted image window.
    mask_window : numpy.ndarray
        Extracted mask window.
    """

    half_size = window_size // 2

    x_min = max(x - half_size, 0)
    x_max = min(x + half_size + 1, image.shape[0])

    y_min = max(y - half_size, 0)
    y_max = min(y + half_size + 1, image.shape[1])

    image_window = image[x_min:x_max, y_min:y_max]
    mask_window = mask[x_min:x_max, y_min:y_max]

    return image_window, mask_window


def get_valid_pixels_from_window(image_window, mask_window):
    """
    Extract valid pixels from a window using the corrupted pixel mask.

    Parameters
    ----------
    image_window : numpy.ndarray
        Local image window.
    mask_window : numpy.ndarray
        Local corrupted pixel mask.

    Returns
    -------
    valid_pixels : numpy.ndarray
        Valid non-corrupted pixels in the window.
    """

    valid_pixels = image_window[~mask_window]
    return valid_pixels

# Gradient-aware directional interpolation

def find_nearest_valid_pixel_along_direction(image, corrupted_mask, x, y, direction, sign, max_radius=25):
    """
    Find the nearest valid pixel along a given direction and sign.

    Parameters
    ----------
    image : numpy.ndarray
        Current restored image.
    corrupted_mask : numpy.ndarray
        Current corrupted pixel mask.
    x : int
        Row index of the target pixel.
    y : int
        Column index of the target pixel.
    direction : tuple
        Direction vector as (dx, dy).
    sign : int
        Direction sign. It must be +1 or -1.
    max_radius : int
        Maximum search radius.

    Returns
    -------
    value : int or None
        Nearest valid pixel value if found, otherwise None.
    """

    height, width = image.shape
    dx, dy = direction

    for radius in range(1, max_radius + 1):
        nx = x + sign * radius * dx
        ny = y + sign * radius * dy

        if nx < 0 or nx >= height or ny < 0 or ny >= width:
            break

        if not corrupted_mask[nx, ny]:
            return int(image[nx, ny])

    return None


def gradient_aware_directional_interpolation(image, corrupted_mask, x, y, max_radius=25):
    """
    Reconstruct a corrupted pixel using gradient-aware directional interpolation.

    Four directions are evaluated:
    - 0 degrees
    - 45 degrees
    - 90 degrees
    - 135 degrees

    The direction with the minimum gradient is selected.

    Parameters
    ----------
    image : numpy.ndarray
        Current restored image.
    corrupted_mask : numpy.ndarray
        Current corrupted pixel mask.
    x : int
        Row index of the target pixel.
    y : int
        Column index of the target pixel.
    max_radius : int
        Maximum radius for searching valid pixels.

    Returns
    -------
    interpolated_value : int
        Reconstructed pixel value.
    """

    directions = {
        "0_degrees": (0, 1),
        "45_degrees": (-1, 1),
        "90_degrees": (-1, 0),
        "135_degrees": (-1, -1)
    }

    candidates = []

    for direction_name, direction_vector in directions.items():
        value_negative = find_nearest_valid_pixel_along_direction(
            image,
            corrupted_mask,
            x,
            y,
            direction_vector,
            sign=-1,
            max_radius=max_radius
        )

        value_positive = find_nearest_valid_pixel_along_direction(
            image,
            corrupted_mask,
            x,
            y,
            direction_vector,
            sign=1,
            max_radius=max_radius
        )

        if value_negative is not None and value_positive is not None:
            gradient_value = abs(value_negative - value_positive)
            interpolated_value = (value_negative + value_positive) / 2.0

            candidates.append(
                {
                    "direction": direction_name,
                    "gradient": gradient_value,
                    "value": interpolated_value
                }
            )

    if len(candidates) > 0:
        best_candidate = min(candidates, key=lambda item: item["gradient"])
        return int(np.clip(round(best_candidate["value"]), 0, 255))

    # Fallback if no valid directional pair exists.
    local_window, local_mask = extract_window_with_mask(
        image,
        corrupted_mask,
        x,
        y,
        window_size=7
    )

    valid_pixels = get_valid_pixels_from_window(local_window, local_mask)

    if valid_pixels.size > 0:
        return int(np.clip(round(np.median(valid_pixels)), 0, 255))

    # Final fallback for extremely rare cases.
    if y > 0:
        return int(image[x, y - 1])
    if x > 0:
        return int(image[x - 1, image.shape[1] - 1])

    return 128

# Corrected Proposed GA-DBRAMF implementation

def apply_ga_dbramf(noisy_image, max_window_size=5, detection_mode="binary", rvin_threshold=45, return_stats=False):
    """
    Apply the proposed Gradient-Aware Decision-Based Recursive Adaptive Median Filter.

    Important design choice:
    The original corrupted mask is kept fixed during filtering. Therefore, only originally
    detected healthy pixels are used as reliable pixels in the 3 x 3 and 5 x 5 windows.
    If no originally healthy pixel exists in the maximum window, gradient-aware directional
    interpolation is used.

    Parameters
    ----------
    noisy_image : numpy.ndarray
        Noisy grayscale image in uint8 format.
    max_window_size : int
        Maximum adaptive search window size. It must be either 3 or 5.
    detection_mode : str
        Corruption detection mode. Options: "binary" or "rvin".
    rvin_threshold : int
        Threshold for RVIN outlier detection.
    return_stats : bool
        If True, return filtering statistics.

    Returns
    -------
    restored_image : numpy.ndarray
        Restored grayscale image.
    stats : dict, optional
        Filtering statistics if return_stats is True.
    """

    if max_window_size not in [3, 5]:
        raise ValueError("For this experiment, max_window_size must be either 3 or 5.")

    restored_image = noisy_image.copy().astype(np.uint8)

    # Keep this mask fixed. It represents the originally detected corrupted pixels.
    original_corrupted_mask = compute_corrupted_mask(
        noisy_image,
        detection_mode=detection_mode,
        rvin_threshold=rvin_threshold
    )

    height, width = noisy_image.shape

    stats = {
        "total_pixels": int(height * width),
        "detected_corrupted_pixels": int(np.sum(original_corrupted_mask)),
        "kept_healthy_pixels": 0,
        "replaced_by_3x3_median": 0,
        "replaced_by_5x5_median": 0,
        "replaced_by_gradient_interpolation": 0
    }

    for x in range(height):
        for y in range(width):

            # If the pixel is originally detected as healthy, keep it unchanged.
            if not original_corrupted_mask[x, y]:
                restored_image[x, y] = noisy_image[x, y]
                stats["kept_healthy_pixels"] += 1
                continue

            replacement_value = None

            # Search originally valid pixels in 3 x 3 window.
            window_3, mask_3 = extract_window_with_mask(
                restored_image,
                original_corrupted_mask,
                x,
                y,
                window_size=3
            )

            valid_pixels_3 = get_valid_pixels_from_window(window_3, mask_3)

            if valid_pixels_3.size > 0:
                replacement_value = np.median(valid_pixels_3)
                stats["replaced_by_3x3_median"] += 1

            # If no originally valid pixel exists and max window is 5, expand to 5 x 5.
            elif max_window_size == 5:
                window_5, mask_5 = extract_window_with_mask(
                    restored_image,
                    original_corrupted_mask,
                    x,
                    y,
                    window_size=5
                )

                valid_pixels_5 = get_valid_pixels_from_window(window_5, mask_5)

                if valid_pixels_5.size > 0:
                    replacement_value = np.median(valid_pixels_5)
                    stats["replaced_by_5x5_median"] += 1

            # If still no originally valid pixel exists, use gradient-aware interpolation.
            if replacement_value is None:
                replacement_value = gradient_aware_directional_interpolation(
                    restored_image,
                    original_corrupted_mask,
                    x,
                    y,
                    max_radius=25
                )
                stats["replaced_by_gradient_interpolation"] += 1

            restored_image[x, y] = np.uint8(np.clip(round(replacement_value), 0, 255))

    if return_stats:
        return restored_image.astype(np.uint8), stats

    return restored_image.astype(np.uint8)

