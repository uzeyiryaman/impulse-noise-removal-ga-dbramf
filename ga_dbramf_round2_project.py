# Utility function for converting images to grayscale uint8 format

def convert_to_grayscale_uint8(image):
    """
    Convert an input image to grayscale uint8 format.

    Parameters
    ----------
    image : numpy.ndarray
        Input image.

    Returns
    -------
    gray_image : numpy.ndarray
        Grayscale image in uint8 format.
    """

    if image.ndim == 3:
        gray_image = cv2.cvtColor(image, cv2.COLOR_RGB2GRAY)
    else:
        gray_image = image.copy()

    if gray_image.dtype != np.uint8:
        gray_image = img_as_ubyte(gray_image)

    return gray_image

