def compute_binary_impulse_mask_fixed(noisy_image):
    """
    Compute corrupted pixel mask for binary impulse noise.
    A pixel is corrupted if it is 0 or 255.
    """
    return (noisy_image == 0) | (noisy_image == 255)


def extract_window_with_mask_fixed(image, mask, x, y, window_size):
    """
    Extract a local image window and the corresponding mask window.
    """
    half_size = window_size // 2

    x_min = max(x - half_size, 0)
    x_max = min(x + half_size + 1, image.shape[0])

    y_min = max(y - half_size, 0)
    y_max = min(y + half_size + 1, image.shape[1])

    image_window = image[x_min:x_max, y_min:y_max]
    mask_window = mask[x_min:x_max, y_min:y_max]

    return image_window, mask_window


def get_valid_pixels_from_window_fixed(image_window, mask_window):
    """
    Extract originally valid pixels from a local window.
    """
    return image_window[~mask_window]


def find_nearest_valid_pixel_along_direction_fixed(image, corrupted_mask, x, y, direction, sign, max_radius=25):
    """
    Find nearest valid pixel along a selected direction.
    """
    height, width = image.shape
    dx, dy = direction

    for radius in range(1, max_radius + 1):
        nx = x + sign * radius * dx
        ny = y + sign * radius * dy

        if nx < 0 or nx >= height or ny < 0 or ny >= width:
            break

        if not corrupted_mask[nx, ny]:
            return int(image[nx, ny])

    return None


def gradient_aware_directional_interpolation_fixed(image, corrupted_mask, x, y, max_radius=25):
    """
    Apply gradient-aware directional interpolation using four directions:
    0, 45, 90, and 135 degrees.
    """
    directions = {
        "0_degrees": (0, 1),
        "45_degrees": (-1, 1),
        "90_degrees": (-1, 0),
        "135_degrees": (-1, -1)
    }

    candidates = []

    for direction_name, direction_vector in directions.items():
        value_negative = find_nearest_valid_pixel_along_direction_fixed(
            image,
            corrupted_mask,
            x,
            y,
            direction_vector,
            sign=-1,
            max_radius=max_radius
        )

        value_positive = find_nearest_valid_pixel_along_direction_fixed(
            image,
            corrupted_mask,
            x,
            y,
            direction_vector,
            sign=1,
            max_radius=max_radius
        )

        if value_negative is not None and value_positive is not None:
            gradient_value = abs(value_negative - value_positive)
            interpolated_value = (value_negative + value_positive) / 2.0

            candidates.append({
                "direction": direction_name,
                "gradient": gradient_value,
                "value": interpolated_value
            })

    if len(candidates) > 0:
        best_candidate = min(candidates, key=lambda item: item["gradient"])
        return int(np.clip(round(best_candidate["value"]), 0, 255))

    # Local median fallback
    local_window, local_mask = extract_window_with_mask_fixed(
        image,
        corrupted_mask,
        x,
        y,
        window_size=7
    )

    valid_pixels = get_valid_pixels_from_window_fixed(local_window, local_mask)

    if valid_pixels.size > 0:
        return int(np.clip(round(np.median(valid_pixels)), 0, 255))

    # Final fallback
    if y > 0:
        return int(image[x, y - 1])
    if x > 0:
        return int(image[x - 1, image.shape[1] - 1])

    return 128


def apply_ga_dbramf_fixed(noisy_image, max_window_size=5, return_stats=False):
    """
    Fixed test version of GA-DBRAMF for binary impulse / structured burst noise.
    The corrupted mask is kept fixed, so gradient-aware fallback can be activated.
    """
    if max_window_size not in [3, 5]:
        raise ValueError("max_window_size must be either 3 or 5.")

    restored_image = noisy_image.copy().astype(np.uint8)

    original_corrupted_mask = compute_binary_impulse_mask_fixed(noisy_image)

    height, width = noisy_image.shape

    stats = {
        "total_pixels": int(height * width),
        "detected_corrupted_pixels": int(np.sum(original_corrupted_mask)),
        "kept_healthy_pixels": 0,
        "replaced_by_3x3_median": 0,
        "replaced_by_5x5_median": 0,
        "replaced_by_gradient_interpolation": 0
    }

    for x in range(height):
        for y in range(width):

            if not original_corrupted_mask[x, y]:
                restored_image[x, y] = noisy_image[x, y]
                stats["kept_healthy_pixels"] += 1
                continue

            replacement_value = None

            window_3, mask_3 = extract_window_with_mask_fixed(
                restored_image,
                original_corrupted_mask,
                x,
                y,
                window_size=3
            )

            valid_pixels_3 = get_valid_pixels_from_window_fixed(window_3, mask_3)

            if valid_pixels_3.size > 0:
                replacement_value = np.median(valid_pixels_3)
                stats["replaced_by_3x3_median"] += 1

            elif max_window_size == 5:
                window_5, mask_5 = extract_window_with_mask_fixed(
                    restored_image,
                    original_corrupted_mask,
                    x,
                    y,
                    window_size=5
                )

                valid_pixels_5 = get_valid_pixels_from_window_fixed(window_5, mask_5)

                if valid_pixels_5.size > 0:
                    replacement_value = np.median(valid_pixels_5)
                    stats["replaced_by_5x5_median"] += 1

            if replacement_value is None:
                replacement_value = gradient_aware_directional_interpolation_fixed(
                    restored_image,
                    original_corrupted_mask,
                    x,
                    y,
                    max_radius=25
                )
                stats["replaced_by_gradient_interpolation"] += 1

            restored_image[x, y] = np.uint8(np.clip(round(replacement_value), 0, 255))

    if return_stats:
        return restored_image.astype(np.uint8), stats

    return restored_image.astype(np.uint8)


