"""## Standard DBRAMF

In this section, the standard Decision-Based Recursive Adaptive Median Filter is implemented as the second baseline method.

The algorithm detects corrupted pixels with binary impulse noise assumption:
- A pixel is considered corrupted if its value is 0 or 255.
- A pixel is considered healthy if its value is between 1 and 254.

If a corrupted pixel has healthy neighbors in a 3 x 3 window, it is replaced by the median of healthy pixels.
If no healthy pixel exists, the window is expanded to 5 x 5.
If the maximum window still contains no healthy pixel, the previous processed pixel is used as fallback.
"""

# Helper functions for Standard DBRAMF

def is_binary_impulse_pixel(pixel_value):
    """
    Check whether a pixel is corrupted under binary impulse noise assumption.

    Parameters
    ----------
    pixel_value : int
        Pixel intensity value.

    Returns
    -------
    is_corrupted : bool
        True if the pixel is 0 or 255, otherwise False.
    """

    return pixel_value == 0 or pixel_value == 255


def extract_window(image, x, y, window_size):
    """
    Extract a local window centered at pixel location (x, y).

    Parameters
    ----------
    image : numpy.ndarray
        Input grayscale image.
    x : int
        Row index.
    y : int
        Column index.
    window_size : int
        Size of the local window.

    Returns
    -------
    window : numpy.ndarray
        Extracted local window.
    """

    half_size = window_size // 2

    x_min = max(x - half_size, 0)
    x_max = min(x + half_size + 1, image.shape[0])

    y_min = max(y - half_size, 0)
    y_max = min(y + half_size + 1, image.shape[1])

    window = image[x_min:x_max, y_min:y_max]

    return window


def get_healthy_pixels_binary(window):
    """
    Extract healthy pixels from a local window using binary impulse noise assumption.

    Parameters
    ----------
    window : numpy.ndarray
        Local image window.

    Returns
    -------
    healthy_pixels : numpy.ndarray
        Pixels with intensity values between 1 and 254.
    """

    healthy_pixels = window[(window > 0) & (window < 255)]

    return healthy_pixels

# Standard DBRAMF implementation

def apply_standard_dbramf(noisy_image, max_window_size=5):
    """
    Apply standard Decision-Based Recursive Adaptive Median Filter.

    Parameters
    ----------
    noisy_image : numpy.ndarray
        Noisy grayscale image in uint8 format.
    max_window_size : int
        Maximum adaptive search window size. It must be either 3 or 5 in this experiment.

    Returns
    -------
    restored_image : numpy.ndarray
        Restored grayscale image.
    """

    if max_window_size not in [3, 5]:
        raise ValueError("For this experiment, max_window_size must be either 3 or 5.")

    height, width = noisy_image.shape
    restored_image = noisy_image.copy().astype(np.uint8)

    for x in range(height):
        for y in range(width):

            current_pixel = noisy_image[x, y]

            # If the pixel is healthy, keep it unchanged.
            if not is_binary_impulse_pixel(current_pixel):
                restored_image[x, y] = current_pixel
                continue

            replacement_value = None

            # First search in 3 x 3 window.
            window_3 = extract_window(restored_image, x, y, window_size=3)
            healthy_pixels_3 = get_healthy_pixels_binary(window_3)

            if healthy_pixels_3.size > 0:
                replacement_value = np.median(healthy_pixels_3)

            # If no healthy pixel exists and max window is 5, expand to 5 x 5.
            elif max_window_size == 5:
                window_5 = extract_window(restored_image, x, y, window_size=5)
                healthy_pixels_5 = get_healthy_pixels_binary(window_5)

                if healthy_pixels_5.size > 0:
                    replacement_value = np.median(healthy_pixels_5)

            # If still no healthy pixel exists, use previous processed pixel.
            if replacement_value is None:
                if y > 0:
                    replacement_value = restored_image[x, y - 1]
                elif x > 0:
                    replacement_value = restored_image[x - 1, width - 1]
                else:
                    replacement_value = 128

            restored_image[x, y] = np.uint8(np.clip(round(replacement_value), 0, 255))

    return restored_image

