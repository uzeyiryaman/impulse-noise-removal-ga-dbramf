def build_mean_std_table(input_df, group_columns):
    """
    Build mean ± std table for MSE, PSNR, SSIM, FOM, and Runtime.
    """
    grouped = input_df.groupby(group_columns).agg(
        MSE_Mean=("MSE", "mean"),
        MSE_Std=("MSE", "std"),
        PSNR_Mean=("PSNR", "mean"),
        PSNR_Std=("PSNR", "std"),
        SSIM_Mean=("SSIM", "mean"),
        SSIM_Std=("SSIM", "std"),
        FOM_Mean=("Pratt_FOM", "mean"),
        FOM_Std=("Pratt_FOM", "std"),
        Runtime_Mean=("Runtime_Seconds", "mean"),
        Runtime_Std=("Runtime_Seconds", "std")
    ).reset_index()

    formatted = grouped[group_columns].copy()

    formatted["MSE"] = grouped.apply(
        lambda row: f"{row['MSE_Mean']:.3f} ± {row['MSE_Std']:.3f}",
        axis=1
    )

    formatted["PSNR"] = grouped.apply(
        lambda row: f"{row['PSNR_Mean']:.3f} ± {row['PSNR_Std']:.3f}",
        axis=1
    )

    formatted["SSIM"] = grouped.apply(
        lambda row: f"{row['SSIM_Mean']:.3f} ± {row['SSIM_Std']:.3f}",
        axis=1
    )

    formatted["Pratt_FOM"] = grouped.apply(
        lambda row: f"{row['FOM_Mean']:.3f} ± {row['FOM_Std']:.3f}",
        axis=1
    )

    formatted["Runtime_Seconds"] = grouped.apply(
        lambda row: f"{row['Runtime_Mean']:.3f} ± {row['Runtime_Std']:.3f}",
        axis=1
    )

    return grouped, formatted


