# Salt-and-Pepper noise function

def add_salt_and_pepper_noise(image, density, random_seed=None):
    """
    Add Salt-and-Pepper noise to a grayscale image.

    Parameters
    ----------
    image : numpy.ndarray
        Input grayscale image in uint8 format.
    density : float
        Noise density between 0 and 1.
    random_seed : int, optional
        Random seed for reproducibility.

    Returns
    -------
    noisy_image : numpy.ndarray
        Noisy grayscale image.
    """

    if random_seed is not None:
        np.random.seed(random_seed)

    noisy_image = image.copy()
    height, width = image.shape

    total_pixels = height * width
    number_of_noisy_pixels = int(density * total_pixels)

    random_indices = np.random.choice(
        total_pixels,
        number_of_noisy_pixels,
        replace=False
    )

    salt_count = number_of_noisy_pixels // 2
    pepper_count = number_of_noisy_pixels - salt_count

    flat_image = noisy_image.flatten()

    salt_indices = random_indices[:salt_count]
    pepper_indices = random_indices[salt_count:salt_count + pepper_count]

    flat_image[salt_indices] = 255
    flat_image[pepper_indices] = 0

    noisy_image = flat_image.reshape(height, width)

    return noisy_image.astype(np.uint8)

# Random-Valued Impulse Noise function

def add_random_valued_impulse_noise(image, density, random_seed=None):
    """
    Add Random-Valued Impulse Noise to a grayscale image.

    Parameters
    ----------
    image : numpy.ndarray
        Input grayscale image in uint8 format.
    density : float
        Noise density between 0 and 1.
    random_seed : int, optional
        Random seed for reproducibility.

    Returns
    -------
    noisy_image : numpy.ndarray
        Noisy grayscale image.
    """

    if random_seed is not None:
        np.random.seed(random_seed)

    noisy_image = image.copy()
    height, width = image.shape

    total_pixels = height * width
    number_of_noisy_pixels = int(density * total_pixels)

    random_indices = np.random.choice(
        total_pixels,
        number_of_noisy_pixels,
        replace=False
    )

    random_values = np.random.randint(
        low=0,
        high=256,
        size=number_of_noisy_pixels,
        dtype=np.uint8
    )

    flat_image = noisy_image.flatten()
    flat_image[random_indices] = random_values

    noisy_image = flat_image.reshape(height, width)

    return noisy_image.astype(np.uint8)

# Structured Burst noise function

def add_structured_burst_noise(image, density, block_size=16, random_seed=None):
    """
    Add Structured Burst Noise to a grayscale image by corrupting connected square blocks.

    Parameters
    ----------
    image : numpy.ndarray
        Input grayscale image in uint8 format.
    density : float
        Approximate noise density between 0 and 1.
    block_size : int
        Size of each corrupted square block.
    random_seed : int, optional
        Random seed for reproducibility.

    Returns
    -------
    noisy_image : numpy.ndarray
        Noisy grayscale image with structured burst corruption.
    """

    if random_seed is not None:
        np.random.seed(random_seed)

    noisy_image = image.copy()
    height, width = image.shape

    total_pixels = height * width
    target_noisy_pixels = int(density * total_pixels)

    corrupted_mask = np.zeros((height, width), dtype=bool)
    corrupted_pixels = 0

    max_attempts = 100000
    attempts = 0

    while corrupted_pixels < target_noisy_pixels and attempts < max_attempts:
        attempts += 1

        x = np.random.randint(0, height - block_size + 1)
        y = np.random.randint(0, width - block_size + 1)

        block_mask = np.zeros((height, width), dtype=bool)
        block_mask[x:x + block_size, y:y + block_size] = True

        new_pixels = np.logical_and(block_mask, ~corrupted_mask)
        number_of_new_pixels = np.sum(new_pixels)

        if number_of_new_pixels == 0:
            continue

        corrupted_mask = np.logical_or(corrupted_mask, block_mask)
        corrupted_pixels = np.sum(corrupted_mask)

    salt_or_pepper = np.random.choice([0, 255], size=(height, width))
    noisy_image[corrupted_mask] = salt_or_pepper[corrupted_mask]

    return noisy_image.astype(np.uint8), corrupted_mask

