def add_salt_and_pepper_noise_with_mask(image, density=0.3, random_seed=42):
    """
    Add Salt-and-Pepper noise and return noisy image + ground-truth corruption mask.
    """
    rng = np.random.default_rng(random_seed)
    noisy_image = image.copy().astype(np.uint8)

    total_pixels = image.size
    number_of_corrupted_pixels = int(round(density * total_pixels))

    corrupted_indices = rng.choice(
        total_pixels,
        size=number_of_corrupted_pixels,
        replace=False
    )

    number_of_salt_pixels = number_of_corrupted_pixels // 2

    salt_indices = corrupted_indices[:number_of_salt_pixels]
    pepper_indices = corrupted_indices[number_of_salt_pixels:]

    noisy_flat = noisy_image.reshape(-1)
    mask_flat = np.zeros(total_pixels, dtype=bool)

    noisy_flat[salt_indices] = 255
    noisy_flat[pepper_indices] = 0
    mask_flat[corrupted_indices] = True

    return noisy_flat.reshape(image.shape).astype(np.uint8), mask_flat.reshape(image.shape)


def add_random_valued_impulse_noise_with_mask(image, density=0.3, random_seed=42):
    """
    Add Random-Valued Impulse Noise and return noisy image + ground-truth corruption mask.
    """
    rng = np.random.default_rng(random_seed)
    noisy_image = image.copy().astype(np.uint8)

    total_pixels = image.size
    number_of_corrupted_pixels = int(round(density * total_pixels))

    corrupted_indices = rng.choice(
        total_pixels,
        size=number_of_corrupted_pixels,
        replace=False
    )

    random_values = rng.integers(
        0,
        256,
        size=number_of_corrupted_pixels,
        dtype=np.uint8
    )

    noisy_flat = noisy_image.reshape(-1)
    mask_flat = np.zeros(total_pixels, dtype=bool)

    noisy_flat[corrupted_indices] = random_values
    mask_flat[corrupted_indices] = True

    return noisy_flat.reshape(image.shape).astype(np.uint8), mask_flat.reshape(image.shape)


def add_structured_burst_noise_with_mask(image, density=0.3, block_size=16, random_seed=42):
    """
    Add Structured Burst Noise and return noisy image + ground-truth corruption mask.
    """
    rng = np.random.default_rng(random_seed)

    noisy_image = image.copy().astype(np.uint8)
    corrupted_mask = np.zeros(image.shape, dtype=bool)

    height, width = image.shape
    target_corrupted_pixels = int(round(density * image.size))

    attempts = 0
    max_attempts = 100000

    while np.sum(corrupted_mask) < target_corrupted_pixels and attempts < max_attempts:
        attempts += 1

        x = rng.integers(0, max(1, height - block_size + 1))
        y = rng.integers(0, max(1, width - block_size + 1))

        x_end = min(x + block_size, height)
        y_end = min(y + block_size, width)

        block_shape = (x_end - x, y_end - y)

        random_binary_values = rng.choice(
            [0, 255],
            size=block_shape
        ).astype(np.uint8)

        noisy_image[x:x_end, y:y_end] = random_binary_values
        corrupted_mask[x:x_end, y:y_end] = True

    return noisy_image.astype(np.uint8), corrupted_mask


